#include "tb_lib.h"

/* checks whether a charector ia an alphabetic letter */

int     my_isalpha(int c)
{
    if ((c >= 'A' && c <= 'Z') || (c >= 'a' && c <= 'z'))
    {
        return (1);
    }
    return (0);
}
