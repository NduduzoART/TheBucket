#include "..\tb_lib.h"

/*
makes a copy of a string
*/

char    *my_strcpy(char *dst, const char *src)
{
    size_t i;

    i = 0;
    while (src[i])
    {
        dst[i] = src[i];
        i++;
    }
    dst[i] = '\0';
    return (dst);
}
