#include "..\tb_lib.h"

/*
prints an unsigned decimal integer
*/

void    my_putunbr(unsigned int n)
{
    if (n > 9)
    {
        my_putunbr(n / 10);
    }
    my_putchar((n % 10) + '0');
}
