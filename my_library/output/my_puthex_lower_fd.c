void    my_puthex_lower_fd(unsigned int n, int fd)
{
    char *base = "0123456789abcdef";

    if (n >= 16)
    {
        my_puthex_lower_fd(n / 16, fd);
    }
    my_putchar_fd(base[n % 16], fd);
}
