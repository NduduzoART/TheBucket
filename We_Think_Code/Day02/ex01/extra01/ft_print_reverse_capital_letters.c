#include <unistd.h>

void	ft_putchar(char c)
{
	write(1, &c, 1);
}

void	ft_print_reverse_capital_letters(void)
{
	char i = 'Z';
	while (i >= 'A')
		{
			ft_putchar(i);
			i--;
		}
}
